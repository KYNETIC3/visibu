"""Build a private Kaggle notebook (script kernel) that pre-trains the sign
encoder on Kaggle's own copy of the asl-signs data, on Kaggle's GPU.

Why: the competition data is already on Kaggle's servers, so nothing has to
be downloaded to this Mac, and the Mac can sleep while it trains. Only
training moves; the app still runs everything on the device.

The kernel embeds this repo's ML code (common/, models/, the importer and the
pre-training script) as a compressed archive, so Kaggle runs exactly the code
that is tested here. It imports the landmarks, pre-trains, evaluates on the
held-out test participants once, and leaves best.pt and the reports in the
kernel's output.

  python -m tools.make_kaggle_kernel --user <kaggle username>
  kaggle kernels push -p exports/kaggle-kernel          # starts the run
  kaggle kernels status <user>/visibu-sign-pretrain
  kaggle kernels output <user>/visibu-sign-pretrain -p checkpoints/pretrain-signs

--job slt builds a second notebook that trains the sentence model on the FULL
How2Sign corpus, using the pre-extracted landmarks Kaggle already hosts
(psewmuthu/how2sign-holistic, see preprocessing/import_how2sign_holistic.py)
and starting from the pre-trained encoder (the output of the notebook above):

  python -m tools.make_kaggle_kernel --user <user> --job slt
  kaggle kernels push -p exports/kaggle-slt
  kaggle kernels output <user>/visibu-slt-how2sign -p checkpoints/slt-how2sign
"""
from __future__ import annotations

import argparse
import base64
import io
import json
import tarfile
from pathlib import Path

ML_ROOT = Path(__file__).resolve().parents[1]
FILES = ["common", "models", "preprocessing/__init__.py", "preprocessing/import_asl_signs.py",
         "training/__init__.py", "training/data.py", "training/pretrain_signs.py"]
SLT_FILES = FILES + ["preprocessing/import_how2sign_holistic.py", "preprocessing/prepare_sequences.py",
                     "preprocessing/build_vocabulary.py", "preprocessing/normalize_landmarks.py",
                     "training/train_slt.py", "training/evaluate.py"]

RUNNER = '''"""Visibu: pre-train the sign encoder on asl-signs (generated by ml/tools/make_kaggle_kernel.py)."""
import base64, io, json, os, shutil, subprocess, sys, tarfile, time
from pathlib import Path

CODE = Path("/kaggle/working/visibu_ml")
DATA = Path("/tmp/asl-signs")            # landmarks: not saved as kernel output
OUT = Path("/kaggle/working/pretrain-signs")
ARGS = __ARGS__

tarfile.open(fileobj=io.BytesIO(base64.b64decode(ARCHIVE))).extractall(CODE)
src = next(p.parent for p in Path("/kaggle/input").rglob("sign_to_prediction_index_map.json"))
print("competition data:", src, flush=True)

def run(*cmd):
    print("$", " ".join(map(str, cmd)), flush=True)
    subprocess.run([sys.executable, "-m", *map(str, cmd)], cwd=CODE, check=True)

t0 = time.time()
run("preprocessing.import_asl_signs", "--src-dir", src, "--out", DATA, "--workers", os.cpu_count() or 4)
OUT.mkdir(parents=True, exist_ok=True)
for f in ("import_report.json", "labels.json"):
    shutil.copy(DATA / f, OUT / f)
hours_left = max(1.0, ARGS["max_hours"] - (time.time() - t0) / 3600)
run("training.pretrain_signs", "--data", DATA, "--out", OUT, "--device", "cuda", "--hours", f"{hours_left:.2f}",
    "--workers", min(4, os.cpu_count() or 2), *ARGS["train"])
run("training.pretrain_signs", "--data", DATA, "--out", OUT, "--device", "cuda", "--evaluate-test",
    "--workers", min(4, os.cpu_count() or 2), *ARGS["train"])
(OUT / "last.pt").unlink(missing_ok=True)  # optimiser state; only best.pt is needed
print("done in", round((time.time() - t0) / 3600, 2), "h", flush=True)
'''


SLT_RUNNER = '''"""Visibu: train the sentence model on full How2Sign (generated by ml/tools/make_kaggle_kernel.py)."""
import base64, io, json, os, shutil, subprocess, sys, tarfile, time
from pathlib import Path

CODE = Path("/kaggle/working/visibu_ml")
DATA = Path("/tmp/h2s")                  # landmarks: not saved as kernel output
OUT = Path("/kaggle/working/slt-how2sign")
ARGS = __ARGS__

tarfile.open(fileobj=io.BytesIO(base64.b64decode(ARCHIVE))).extractall(CODE)
src = next(p.parent.parent for p in Path("/kaggle/input").rglob("how2sign_realigned_train.csv"))
pre = next(p for p in Path("/kaggle/input").rglob("best.pt") if p.parent.name == "pretrain-signs")
print("landmarks:", src, "pre-trained encoder:", pre, flush=True)
workers = os.cpu_count() or 4

def run(*cmd, check=True):
    print("$", " ".join(map(str, cmd)), flush=True)
    return subprocess.run([sys.executable, "-m", *map(str, cmd)], cwd=CODE, check=check).returncode

t0 = time.time()
run("preprocessing.import_how2sign_holistic", "--src", src, "--out", DATA, "--workers", workers)
run("preprocessing.prepare_sequences", "--root", DATA)
run("preprocessing.build_vocabulary", "--root", DATA, "--out", DATA / "prepared" / "vocab.json")
run("preprocessing.normalize_landmarks", "--prepared", DATA / "prepared")
OUT.mkdir(parents=True, exist_ok=True)
shutil.copy(DATA / "import_report.json", OUT / "import_report.json")
for f in ("vocab.json", "prep_config.json", "feature_stats.json"):
    shutil.copy(DATA / "prepared" / f, OUT / f)
hours_left = max(1.0, ARGS["max_hours"] - (time.time() - t0) / 3600)
run("training.train_slt", "--prepared", DATA / "prepared", "--out", OUT, "--device", "cuda", "--init-encoder", pre,
    "--hours", f"{hours_left:.2f}", "--workers", min(4, workers), *ARGS["train"])
(OUT / "last.pt").unlink(missing_ok=True)  # optimiser state; only best.pt is needed
# Validation report (needs sacrebleu / rouge-score; skipped if this image lacks them).
run("training.evaluate", "--checkpoint", OUT / "best.pt", "--prepared", DATA / "prepared", "--split", "val",
    "--device", "cuda", "--out", OUT / "eval_val.json", check=False)
print("done in", round((time.time() - t0) / 3600, 2), "h", flush=True)
'''


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--user", required=True, help="Kaggle username")
    ap.add_argument("--job", choices=["pretrain", "slt"], default="pretrain")
    ap.add_argument("--slug", help="default: visibu-sign-pretrain / visibu-slt-how2sign")
    ap.add_argument("--out", type=Path, help="default: exports/kaggle-kernel / exports/kaggle-slt")
    ap.add_argument("--max-hours", type=float, default=11.0, help="Kaggle stops runs at 12 h; leave a margin")
    ap.add_argument("train_args", nargs="*", help="extra pretrain_signs.py arguments, after --")
    args = ap.parse_args()
    slt = args.job == "slt"
    args.slug = args.slug or ("visibu-slt-how2sign" if slt else "visibu-sign-pretrain")
    args.out = args.out or ML_ROOT / "exports" / ("kaggle-slt" if slt else "kaggle-kernel")

    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for rel in (SLT_FILES if slt else FILES):
            p = ML_ROOT / rel
            for f in ([p] if p.is_file() else sorted(p.rglob("*.py"))):
                tar.add(f, arcname=str(f.relative_to(ML_ROOT)))
    archive = base64.b64encode(buf.getvalue()).decode()
    runner = (SLT_RUNNER if slt else RUNNER).replace("__ARGS__", json.dumps({"max_hours": args.max_hours, "train": args.train_args}))
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "run.py").write_text(f'ARCHIVE = "{archive}"\n' + runner)
    meta = {
        "id": f"{args.user}/{args.slug}", "title": args.slug, "code_file": "run.py", "language": "python",
        "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_internet": False,
        "competition_sources": [] if slt else ["asl-signs"],
        "dataset_sources": ["psewmuthu/how2sign-holistic"] if slt else [],
        "kernel_sources": [f"{args.user}/visibu-sign-pretrain"] if slt else [],
    }
    (args.out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
    print(f"wrote {args.out} (code archive {len(archive) // 1024} KB)")


if __name__ == "__main__":
    main()
